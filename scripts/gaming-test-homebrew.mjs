import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const root='apps/jhadina-web/public/gaming/gameboy/homebrew/';
const rom=readFileSync(root+'2048.gb');
const sourceBlob='9bae43c7c020af603c64e4e049064e5cbfb183f8';
assert.equal(rom.length,32768,'homebrew ROM must remain the pinned 32 KB release');
const blobSha=createHash('sha1').update('blob '+rom.length).update(Uint8Array.of(0)).update(rom).digest('hex');
assert.equal(blobSha,sourceBlob,'ROM changed from verified author source');
const title=rom.subarray(0x134,0x143).toString('ascii').split(String.fromCharCode(0))[0];
assert.equal(title,'2048','Game Boy title header mismatch');
let sum=0;
for(let i=0x134;i<=0x14c;i++)sum=(sum-rom[i]-1)&255;
assert.equal(sum,rom[0x14d],'ROM title/header checksum mismatch');
assert.equal(rom[0x147],0,'Expected fixed/no-MBC cartridge');
assert.equal(rom[0x148],0,'Expected 32 KiB ROM size marker');
const license=readFileSync(root+'LICENSE','utf8');
assert(license.includes('MIT License')&&license.includes('Wyatt Ferguson'),'Bundled ROM license/notice missing');
const page=readFileSync('apps/jhadina-web/public/gaming/gameboy/index.html','utf8');
assert(page.includes('href="/gaming/gameboy/homebrew/2048.gb"'));
assert(page.includes('download="2048.gb"'));
assert(page.includes('Import .gb / .gbc / .zip'), 'Phone importer must advertise direct local ZIP support');
console.log('PASS: MIT homebrew 2048.gb matches original Git blob, 32 KiB Game Boy cartridge header, and attribution');
